  || E'   - 3개 AI(GPT·Gemini·Claude)의 주간 평균 적중률을 넘긴 분들 중 추첨 1명\n\n'
  || E'🎁 참여상 · 메가커피 5,000원 쿠폰 (3명)\n'
  || E'   - 한 주 5경기 이상 예측한 참여자 전원 중 추첨 3명\n'
