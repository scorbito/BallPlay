--
-- 사전 조건: public.bp_notices 가 존재해야 함.
-- 본 SQL은 idempotent — 같은 제목 공지가 이미 있으면 재삽입하지 않음.
-- Supabase SQL Editor에서 1회 실행. published_at = now() 이므로 실행 즉시 게시됨.
