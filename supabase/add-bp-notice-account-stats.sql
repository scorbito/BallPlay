-- 야구놀이터 업데이트 공지 (2026-06-03) — 계정 누적 전적 신설 + 라인업 전적과 분리.
--   - 신규 "계정 누적 전적" 도입: 모두 0승 0패에서 새로 시작.
--   - 계정 누적은 본인이 직접 플레이한 경기만 누적 (자고 있을 때 변동 없음).
--   - 라인업 전적은 기존 그대로 — 본인이 안 해도 다른 분이 도전하면 누적되고 내 기록에 표시.
--
-- 사전 조건: add-bp-notices.sql 가 실행되어 public.bp_notices 가 존재해야 함.
-- 본 SQL은 idempotent — 같은 제목 공지가 이미 있으면 재삽입하지 않음.
-- Supabase SQL Editor에서 1회 실행.

insert into public.bp_notices (title, body, published_at)
select
  '계정 누적 전적이 새로 생겼어요!',
  E'안녕하세요, 야구놀이터입니다 ⚾\n\n'
  || E'전적 누적 방식을 두 가지로 분리했어요. 헷갈리지 않게 정리해드릴게요.\n\n'
  || E'🆕 계정 누적 전적 (0승 0패에서 새 출발)\n'
  || E'   본인이 직접 대전한 경기만 누적됩니다.\n'
  || E'   누군가 내 라인업에 도전했을 때는 변동 없어요.\n'
  || E'   모든 사용자가 같은 출발선(0승 0패)에서 시작합니다.\n\n'
  || E'📊 라인업 전적 (기존 방식 유지)\n'
  || E'   라인업 자체의 전적이라, 본인이 직접 안 해도 누군가 내 라인업으로\n'
  || E'   대전을 진행하면 결과가 누적됩니다.\n'
  || E'   상대가 도전한 매치도 "내 기록"에 그대로 쌓여서 확인 가능해요.\n\n'
  || E'🏆 영향 받는 화면\n'
  || E'   • 홈 히어로 뱃지 "📊 내 매치 기록 N승 N패 · N위" → 계정 누적 기준\n'
  || E'   • 계정 누적 랭킹 (/play/account-ranking) → 계정 누적 기준\n'
  || E'   • 라인업 랭킹 (/play/lineup/ranking) → 라인업 전적 기준 (변경 없음)\n'
  || E'   • 내 기록 (/records) → 라인업 전적 기준 (변경 없음)\n\n'
  || E'기존 활성 사용자분들도 계정 누적은 다시 0부터 쌓이는 점 양해 부탁드려요.\n'
  || E'본인의 실력을 직관적으로 보여드리기 위한 변경입니다.\n\n'
  || E'— 야구놀이터 드림',
  now()        -- published_at: 즉시 게시 (정렬 기준)
where not exists (
  select 1 from public.bp_notices
  where title = '계정 누적 전적이 새로 생겼어요!'
);

