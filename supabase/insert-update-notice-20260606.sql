-- 야구놀이터 업데이트 공지 (2026-06-06)
--   - 팀 운영 모델 전환(라인업→팀 관리), 출전 중 수정, 전적 초기화 없음,
--     홈/원정 전적 분리, 팀 은퇴, 마이페이지 신설(내 기록 편입).
--
-- 사전 조건: add-bp-notices.sql 가 실행되어 public.bp_notices 가 존재해야 함.
-- 본 SQL은 idempotent — 같은 제목 공지가 이미 있으면 재삽입하지 않음.
-- Supabase SQL Editor에서 1회 실행. 게시 후 7일간 NEW 뱃지 자동 표시.

insert into public.bp_notices (title, body, published_at)
select
  '업데이트 — 라인업이 팀 운영으로, 마이페이지 신설',
  E'안녕하세요, 야구놀이터입니다 ⚾\n\n'
  || E'"라인업 짜기"가 "팀 관리"로 새로워졌어요.\n'
  || E'한 번 짜고 끝이 아니라, 내 팀을 계속 키워가는 방식으로 바뀌었습니다.\n\n'
  || E'🏟️ 라인업 → 팀 운영\n'
  || E'   슬롯 하나가 곧 하나의 팀이에요. 같은 구단은 한 번만 만들 수 있어요.\n\n'
  || E'✏️ 출전 중에도 라인업 자유 수정\n'
  || E'   이제 경기장에 출전 중이어도 선수 교체·타순 변경이 자유로워요. (팀 자체는 변경 불가)\n\n'
  || E'🔁 전적 초기화 없음\n'
  || E'   출전을 내리거나 라인업을 바꿔도 쌓은 전적은 그대로 유지됩니다.\n\n'
  || E'🥇 홈·원정 전적 분리\n'
  || E'   홈 전적은 내가 직접 실행한 경기, 원정 전적은 다른 분이 내 팀에 도전한 경기예요.\n\n'
  || E'🎖️ 팀 은퇴\n'
  || E'   전적이 있는 팀은 삭제 대신 은퇴로 보관돼요. 전적과 최종 라인업이 그대로 남고,\n'
  || E'   마이페이지에서 다시 볼 수 있어요. (경기 기록 없는 팀은 그냥 삭제)\n\n'
  || E'👤 마이페이지 신설\n'
  || E'   하단 "마이" 메뉴에서 누적 전적·내 팀 요약·은퇴한 팀을 한눈에.\n'
  || E'   "내 기록"도 이제 마이페이지 안에서 볼 수 있어요.\n\n'
  || E'🔧 그 외 개선\n'
  || E'   동기화 안정화, "앱으로 설치"는 설정 페이지로 이동, 디자인 정리.\n\n'
  || E'앞으로도 더 재미있는 야구놀이터로 찾아뵐게요. 의견은 언제든 환영이에요!\n\n'
  || E'— 야구놀이터 드림',
  now()        -- published_at: 즉시 게시 (정렬 기준)
where not exists (
  select 1 from public.bp_notices
  where title = '업데이트 — 라인업이 팀 운영으로, 마이페이지 신설'
);

